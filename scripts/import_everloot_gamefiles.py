"""Import Everloot's *separate* client-game-file export without mixing licenses.

Consumes game-files/*.ndjson and the export manifest.json. The published
game-files layer is Blizzard game data, NOT CC BY-SA player observations.
Only items relevant to Fishing Atlas and Cooking/Fishing recipes are shipped by
default. Use --all-professions to stage all client recipe edges (unconfirmed).
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

from build_catalog import ROOT, lua

CREDIT = ("Game data © Blizzard Entertainment, Inc., read from the public client; "
          "not under Everloot's licence. Column names from WoWDBDefs "
          "(https://github.com/wowdev/WoWDBDefs), CC BY-SA 4.0.")
OUTPUT = ROOT / "FishingAtlas" / "Data" / "EverlootGameFiles.lua"
JSON = ROOT / "database" / "game-files" / "everloot-gamefiles.json"
TARGET = "1.60.1.70888"


def read_file(export, filename, manifest):
    path = export / "game-files" / (filename + ".ndjson")
    if not path.exists():
        raise ValueError("Missing client dataset: " + str(path))
    raw = path.read_bytes()
    for info in manifest.get("files", []):
        if info.get("path") == "game-files/" + filename + ".ndjson" and info.get("layer") == "game-files":
            if info.get("sha256") != hashlib.sha256(raw).hexdigest():
                raise ValueError("Client export checksum mismatch: " + filename)
            break
    else:
        raise ValueError("Missing manifest checksum: " + filename)
    return [json.loads(row) for row in raw.decode("utf-8").splitlines() if row.strip()]


def build(export, all_professions=False):
    manifest = json.loads((export / "manifest.json").read_text(encoding="utf-8"))
    game = manifest.get("gameFiles", {})
    game_build = game.get("version") if isinstance(game, dict) else None
    if game_build != TARGET:
        raise ValueError("Wrong client build, expected " + TARGET + ", got " + str(game_build))
    catalog = json.loads((ROOT / "database" / "catalog.json").read_text(encoding="utf-8"))
    observed_path = ROOT / "database" / "observed" / "everloot-normalized.json"
    observed = json.loads(observed_path.read_text(encoding="utf-8")) if observed_path.exists() else {}
    tracked = {e["id"] for e in catalog.get("entities", []) if e.get("type") == "item"}
    for key in ("vendorItems", "drops", "fishing", "poolItems", "itemNames"):
        tracked.update(int(i) for i in observed.get(key, {}))
    recipes, categories, relations = {}, {}, []
    for row in read_file(export, "recipes", manifest):
        if not all_professions and row.get("professionName") not in ("Cooking", "Fishing"):
            continue
        if row.get("build") != TARGET:
            continue
        spell, output_id = row.get("spellId"), row.get("itemId")
        if type(spell) is int and spell > 0:
            recipes[spell] = {
                "profession": row.get("professionName"), "outputItemId": output_id,
                "minimumSkill": row.get("minRank"),
                "reagents": row.get("reagents", [])}
            if type(output_id) is int and output_id > 0:
                tracked.add(output_id)
            for reagent in row.get("reagents", []):
                if isinstance(reagent, dict) and type(reagent.get("itemId")) is int:
                    tracked.add(reagent["itemId"])
    for row in read_file(export, "item-categories", manifest):
        item_id = row.get("itemId")
        if item_id in tracked:
            categories[item_id] = {
                "classId": row.get("classId"), "subclassId": row.get("subclassId"),
                "className": row.get("className"), "subclassName": row.get("subclassName"),
                "slot": row.get("slot"), "qualityName": row.get("qualityName")}
    for row in read_file(export, "relations", manifest):
        if row.get("build") != TARGET:
            continue
        if (row.get("fromKind") == "item" and row.get("fromId") in tracked) or (
            row.get("toKind") == "item" and row.get("toId") in tracked):
            relations.append({k: row.get(k) for k in
                ("fromKind", "fromId", "toKind", "toId", "rel")})
    return {"meta": {"source": "Everloot open client game-file export",
                     "sourceUrl": "https://everloot.app/database/download",
                     "credit": CREDIT, "build": TARGET,
                     "status": "game_files_unconfirmed"},
            "categories": categories, "recipes": recipes,
            "relations": relations}


def game_lua(value):
    return ("-- Game data © Blizzard Entertainment, Inc.\n"
            "-- Found in game files, UNCONFIRMED. NOT CC BY-SA Everloot observed data.\n"
            "-- Generated by scripts/import_everloot_gamefiles.py\n"
            "local _, ns = ...\nns.data.gameFiles = " + lua(value) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export", type=Path, required=True)
    parser.add_argument("--all-professions", action="store_true")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = build(args.export, args.all_professions)
    lua_text = game_lua(result)
    json_text = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != lua_text:
            raise ValueError("Generated game-file Lua differs from the selected export")
        if JSON.read_text(encoding="utf-8") != json_text:
            raise ValueError("Game-file JSON differs from the selected export")
    else:
        JSON.parent.mkdir(parents=True, exist_ok=True)
        JSON.write_text(json_text, encoding="utf-8")
        OUTPUT.write_text(lua_text, encoding="utf-8")
    print("Unconfirmed game-file recipes:", len(result["recipes"]),
          "tracked categories:", len(result["categories"]),
          "relations:", len(result["relations"]))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print("Game-file import error:", error, file=sys.stderr)
        sys.exit(1)
