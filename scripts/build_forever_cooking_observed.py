"""Build the offline Fishing Atlas Cooking teacher/vendor observation index.

Observed EG Link sources are independently version-stamped, NOT current-server
promises. Upstream is CC BY 4.0; preserve attribution and exact source commit.
Use --check offline in CI; --refresh updates local snapshots from pinned GitHub.
"""
import argparse
import json
import re
from pathlib import Path
from urllib.request import Request, urlopen
from build_catalog import lua

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "database" / "observed" / "eg-cooking.json"
OUTPUT = ROOT / "FishingAtlas" / "Data" / "ForeverObservedCooking.lua"
REPO = "JIVESCORP/eg-link-output-wowf"
PIN = "ea970da071079b32e56f349e09648ff0e314b351"
BUILDS = ["70938","70888","70862","70840","70450","70338","70205"]
HEADER = "-- SPDX-License-Identifier: GPL-3.0-or-later\n-- Observed world data from Efficient Games EG Link, CC BY 4.0.\n-- Source/build metadata is retained in ns.data.foreverObservedCooking.meta.\n-- Generated by scripts/build_forever_cooking_observed.py; DO NOT EDIT.\nlocal _, ns = ...\nns.data.foreverObservedCooking = "

def valid(position):
    return isinstance(position, dict) and isinstance(position.get("uiMap"), int) \
        and position["uiMap"] > 0 and all(isinstance(position.get(k), (int, float))
        and 0 <= position[k] <= 1 for k in ("mapX", "mapY"))

def normalize(name):
    return re.sub(r"[^a-z0-9]+", " ", re.sub(
        r"^recipe:\s*", "", name.lower())).strip()

def fetch_json(build, kind):
    path = f"data/wowf/1.60.1.{build}/{kind}.json"
    url = f"https://raw.githubusercontent.com/{REPO}/{PIN}/{path}"
    raw = urlopen(Request(url, headers={
        "User-Agent": "FishingAtlas-EG-cooking-import/0.99.7"
    }), timeout=30).read(3_000_000)
    obj = json.loads(raw)
    meta = obj.get("meta", {})
    if meta.get("product") != "wowf" or meta.get("license") != "CC BY 4.0" \
        or meta.get("clientBuild") != "1.60.1." + build:
        raise ValueError("EG Link build/license/source mismatch: " + path)
    return path, obj

def refresh():
    catalog = json.loads((ROOT / "database" / "catalog.json").read_text())
    recipe_ids = {r["spellId"] for r in catalog["recipes"]
                  if r.get("profession") == "Cooking"}
    trainers, vendors, seen_trainers, seen_vendors, paths = {}, {}, set(), set(), []
    for build in BUILDS:
        pt, ts = fetch_json(build, "trainers")
        pv, vs = fetch_json(build, "vendors")
        paths.extend((pt, pv))
        for npcid, npc in ts["trainers"].items():
            for spell, service in npc.get("services", {}).items():
                spellid = service.get("spellId", int(spell))
                if spellid not in recipe_ids or service.get("skill") != "Cooking":
                    continue
                key = (spellid, npcid)
                if key in seen_trainers: continue
                seen_trainers.add(key)
                point = next((p for p in npc.get("positions", []) if valid(p)), None)
                row = {"npcId": int(npcid), "name": npc.get("name") or "NPC " + npcid,
                       "sourceBuild": "1.60.1." + build,
                       "seenOn": npc.get("lastSeen"), "installs": service.get("sources") or 1}
                if isinstance(service.get("skillRank"), int):
                    row["skillRank"] = service["skillRank"]
                if point: row.update(mapID=point["uiMap"], x=point["mapX"], y=point["mapY"])
                trainers.setdefault(str(spellid), []).append(row)
        for npcid, npc in vs["vendors"].items():
            for entry in npc.get("entries", {}).values():
                if not entry.get("name", "").lower().startswith("recipe: ") \
                    or not isinstance(entry.get("itemId"), int): continue
                dish = normalize(entry["name"])
                key = (entry["itemId"], npcid)
                if key in seen_vendors: continue
                seen_vendors.add(key)
                point = next((p for p in npc.get("positions", []) if valid(p)), None)
                row = {"itemId": entry["itemId"], "itemName": entry["name"],
                       "npcId": int(npcid), "name": npc.get("name") or "NPC " + npcid,
                       "sourceBuild": "1.60.1." + build,
                       "seenOn": npc.get("lastSeen"), "installs": entry.get("sources") or 1}
                if point: row.update(mapID=point["uiMap"], x=point["mapX"], y=point["mapY"])
                vendors.setdefault(dish, []).append(row)
    for group in (trainers, vendors):
        for rows in group.values(): rows.sort(key=lambda x: (
            tuple(-int(v) for v in x["sourceBuild"].split(".")), x["npcId"]))
    result = {
        "meta": {
            "source": "Efficient Games EG Link: observed Forever trainer menus and vendor stock",
            "sourceUrl": "https://github.com/" + REPO + "/tree/" + PIN + "/data/wowf",
            "sourceCommit": PIN, "license": "CC BY 4.0",
            "attribution": "Data from Efficient Games (https://efficient.games), licensed under CC BY 4.0.",
            "clientBuilds": ["1.60.1." + b for b in BUILDS],
            "sourceFiles": paths,
            "notes": "Multiple client-build observations, NOT guarantee of today's current stock or teachability."
        },
        "trainers": trainers, "vendors": vendors
    }
    INPUT.parent.mkdir(parents=True, exist_ok=True)
    INPUT.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
    return result

def pretty_lua(value, depth=0):
    # Stable, readable Lua 5.1; multi-line data avoids Luacheck 631 and makes
    # a review of source coordinates/provenance practical.
    if not isinstance(value, (list, dict)):
        return lua(value)
    pad, indent = "  " * depth, "  " * (depth + 1)
    lines = []
    if isinstance(value, list):
        lines = [indent + pretty_lua(item, depth + 1) + "," for item in value]
    else:
        for key in sorted(value):
            attr = key if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key) \
                else "[" + lua(key) + "]"
            lines.append(indent + attr + " = " +
                         pretty_lua(value[key], depth + 1) + ",")
    return "{\\n".replace("\\\\n", "\\n") + "\\n".join(lines) + "\\n" + pad + "}"

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = refresh() if args.refresh else json.loads(INPUT.read_text())
    if raw["meta"]["sourceCommit"] != PIN or raw["meta"]["license"] != "CC BY 4.0":
        raise ValueError("Unexpected source commit or license")
    generated = HEADER + pretty_lua(raw) + "\n"
    if args.check:
        if OUTPUT.read_text() != generated: raise ValueError("EG Cooking source is stale")
    else:
        OUTPUT.write_text(generated)
    print("EG Cooking: %d trainer recipes and %d vendor dish names" % (
        len(raw["trainers"]), len(raw["vendors"])))

if __name__ == "__main__":
    main()
